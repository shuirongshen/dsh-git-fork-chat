/**
 * Build the dual-face DSH plugin.
 *
 * - Host half: ESM Node bundle at lib/index.js.
 * - Client half: CJS bundle wrapped in the `window.__ModuleLoader__.load`
 *   factory contract used by the DSH web client module system. React and the
 *   DSH shared modules stay external; React Flow and Dagre are bundled.
 *
 * The native esbuild binary is invoked with stdio:"inherit" instead of the
 * esbuild JS API. Under the DSH Windows sandbox, child processes using pipe
 * stdio are denied (EPERM), while inherited stdio works normally.
 */
import { spawnSync } from 'node:child_process'
import { mkdir, readFile, rm, writeFile } from 'node:fs/promises'
import { existsSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = dirname(dirname(fileURLToPath(import.meta.url)))
const pkg = JSON.parse(await readFile(join(root, 'package.json'), 'utf8'))
const libDir = join(root, 'lib')
const esbuild = join(root, 'node_modules', '@esbuild', 'win32-x64', 'esbuild.exe')

const sharedExternal = [
  'react',
  'react-dom',
  'react/jsx-runtime',
  'react/jsx-dev-runtime',
  '@deepseek-ai/*',
]

/** Run esbuild with inherited stdio and fail loudly. */
function runEsbuild(args) {
  const result = spawnSync(esbuild, args, { cwd: root, stdio: 'inherit' })
  if (result.error !== undefined) throw result.error
  if (result.status !== 0) throw new Error(`esbuild exited with ${String(result.status)}`)
}

/** Build the host-side ESM module. */
async function buildHost() {
  runEsbuild([
    'src/host/index.ts',
    '--bundle',
    '--platform=node',
    '--format=esm',
    '--target=node22',
    '--packages=external',
    '--outfile=lib/index.js',
    '--log-level=error',
    '--legal-comments=none',
  ])
  const text = await readFile(join(libDir, 'index.js'), 'utf8')
  console.log(`[build] host  lib/index.js  ${(Buffer.byteLength(text) / 1024).toFixed(1)} KiB`)
}

/** Build the browser-side CJS bundle and wrap it for the DSH loader. */
async function buildClient() {
  const entry = join(root, 'src/client/index.tsx')
  if (!existsSync(entry)) {
    console.warn('[build] client entry missing; skipped client build')
    return
  }
  const bodyFile = join(libDir, 'client.body.js')
  const args = [
    'src/client/index.tsx',
    '--bundle',
    '--platform=browser',
    '--format=cjs',
    '--target=chrome110',
    '--jsx=automatic',
    '--loader:.css=text',
    '--charset=utf8',
    '--log-level=error',
    '--legal-comments=none',
    '--define:process.env.NODE_ENV="production"',
    `--outfile=${bodyFile}`,
  ]
  for (const external of sharedExternal) {
    if (external.includes('*')) {
      // esbuild's --external accepts wildcards; keep the literal pattern.
      args.push(`--external:${external}`)
    } else {
      args.push(`--external:${external}`)
    }
  }
  runEsbuild(args)
  const body = await readFile(bodyFile, 'utf8')
  const wrapped = `/* ${pkg.name}@${pkg.version} — client half, generated by scripts/build.mjs */
window.__ModuleLoader__.load({
  id: ${JSON.stringify(pkg.name)},
  factory: (require) => {
    var module = { exports: {} };
    var exports = module.exports;
${body}
    return module.exports;
  }
});
`
  await writeFile(join(libDir, 'client.js'), wrapped, 'utf8')
  await rm(bodyFile, { force: true })
  console.log(`[build] client lib/client.js ${(Buffer.byteLength(wrapped) / 1024).toFixed(1)} KiB`)
}

await mkdir(libDir, { recursive: true })
const only = process.argv[2]
if (only !== 'client') await buildHost()
if (only !== 'host') await buildClient()
